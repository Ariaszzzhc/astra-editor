set_project("astra")
set_version("0.1.0")
set_xmakever("3.1.1")
set_languages("c++23")
set_encodings("utf-8")
set_warnings("allextra", "error")
-- Freeze the whole recipe tree, including hashes, in dependencies.lock.json.
-- xmake 3.1.1's additional Git partial-clone lock path is not used.
set_policy("package.requires_lock", false)
add_repositories("astra-pinned .tools/recipes/xmake-repo-e567b25f0575b952c47b2000e0dedbd6fa698b2c")
includes("xmake/packages/astra-sdl3/xmake.lua")
includes("xmake/packages/skia-graphite/xmake.lua")

add_rules("mode.debug", "mode.release")

if is_plat("windows") then
    -- Skia's bundled Dawn uses /MT in both configurations. Keep one CRT ABI.
    set_runtimes("MT")
    add_defines("NOMINMAX", "WIN32_LEAN_AND_MEAN", "_ITERATOR_DEBUG_LEVEL=0")
    add_cxxflags("/permissive-", {tools = {"cl", "clang_cl"}})
    if is_mode("debug") then
        -- Embed CodeView records in objects; avoid a shared compiler PDB server.
        set_symbols("debug", "embed")
    end
end

add_requires("doctest 2.4.12", {system = false})
add_requires("nlohmann_json 3.12.0", {system = false})
add_requires("libuv 1.52.1", "quickjs-ng 0.15.1", "tree-sitter 0.26.13", "utf8proc 2.11.3", {system = false})
add_requires("astra-sdl3 3.4.12", {alias = "libsdl3", system = false, configs = {shared = true}})
if is_plat("windows") then
    add_requireconfs("*", {configs = {runtimes = "MT"}})
end
add_requires("skia-graphite", {configs = {root = os.projectdir(),
    configuration = is_mode("debug") and "Debug" or "Release", runtimes = "MT"}})

target("astra-core")
    set_kind("static")
    add_includedirs("include", {public = true})
    add_headerfiles("include/(astra/core/*.hpp)")
    add_files("src/core/*.cpp")
    set_exceptions("cxx")

target("astra-tests")
    set_kind("binary")
    set_default(true)
    add_deps("astra-core", "astra-protocol", "astra-io", "astra-service", "astra-config", "astra-script", "astra-transport", "astra-workspace", "astra-editing")
    add_packages("doctest")
    add_files("tests/main.cpp", "tests/sum_tree_tests.cpp", "tests/rope_tests.cpp", "tests/document_tests.cpp",
              "tests/framing_tests.cpp", "tests/file_store_tests.cpp", "tests/rpc_tests.cpp", "tests/service_tests.cpp",
              "tests/editor_config_tests.cpp", "tests/script_tests.cpp", "tests/tcp_tests.cpp", "tests/workspace_tests.cpp", "tests/editing_tests.cpp",
              "tests/application_tests.cpp", "tests/tcp_client_tests.cpp")
    set_exceptions("cxx")
    add_tests("unit", {runargs = {"--no-version", "--duration=true"}})

target("astra-core-tests")
