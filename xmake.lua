rule("astra.resources")
    after_build(function (target)
        os.cp(path.join(os.projectdir(), "data"), target:targetdir())
    end)
    after_install(function (target)
        os.cp(path.join(os.projectdir(), "data"), path.join(target:installdir(), "bin"))
    end)

